// Best-effort detection of an E.164 country code from the phone number.
// Returns a string like "+237", "+33", "+1". Falls back to assuming a
// 3-digit code when nothing matches (rare).
const KNOWN_CODES = [
  '1', '7', '20', '27', '30', '31', '32', '33', '34', '36', '39', '40',
  '41', '43', '44', '45', '46', '47', '48', '49', '51', '52', '53', '54',
  '55', '56', '57', '58', '60', '61', '62', '63', '64', '65', '66', '81',
  '82', '84', '86', '90', '91', '92', '93', '94', '95', '98',
  '210', '211', '212', '213', '216', '218', '220', '221', '222', '223',
  '224', '225', '226', '227', '228', '229', '230', '231', '232', '233',
  '234', '235', '236', '237', '238', '239', '240', '241', '242', '243',
  '244', '245', '246', '248', '249', '250', '251', '252', '253', '254',
  '255', '256', '257', '258', '260', '261', '262', '263', '264', '265',
  '266', '267', '268', '269', '290', '291', '297', '298', '299',
  '350', '351', '352', '353', '354', '355', '356', '357', '358', '359',
  '370', '371', '372', '373', '374', '375', '376', '377', '378', '380',
  '381', '382', '383', '385', '386', '387', '389', '420', '421', '423',
];

export function extractCountryCode(phoneE164: string): string {
  if (!phoneE164.startsWith('+')) return '+237';
  const digits = phoneE164.slice(1);
  for (const len of [3, 2, 1]) {
    const candidate = digits.slice(0, len);
    if (KNOWN_CODES.includes(candidate)) return '+' + candidate;
  }
  // Fallback: assume 3-digit code (cap at column width 5).
  return '+' + digits.slice(0, 3);
}
